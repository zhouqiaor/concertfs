#!/usr/bin/env python3
"""从契约 ErrorBody.code enum 生成 Go / Kotlin 错误码常量（同源，确定性输出）。

枚举只在 contract/openapi/phonefs.yaml 的 `components.schemas.ErrorBody`
`properties.code.enum` 定义一次；客户端合成码不在其中，也不在此生成。

用法（默认值相对 scripts/ 目录，可重复运行、零 diff）：
  python gen_error_codes.py
  python gen_error_codes.py --yaml <path> --go <path> --kotlin <path>
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

import yaml

SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
PROJECT_DIR = SCRIPT_DIR.parent

DEFAULT_YAML = PROJECT_DIR / "contract" / "openapi" / "phonefs.yaml"
DEFAULT_GO = PROJECT_DIR / "go" / "internal" / "fsprovider" / "error_codes.gen.go"
DEFAULT_KOTLIN = (
    PROJECT_DIR
    / "android"
    / "core-protocol"
    / "src"
    / "main"
    / "kotlin"
    / "com"
    / "phonefs"
    / "core"
    / "protocol"
    / "ErrCodes.gen.kt"
)

PROVENANCE = (
    "Code generated by projects/phonefs/scripts/gen_error_codes.py from\n"
    "projects/phonefs/contract/openapi/phonefs.yaml. DO NOT EDIT."
)


def camel_case(code: str) -> str:
    return "".join(part.capitalize() for part in code.split("_"))


def load_codes(path: pathlib.Path) -> tuple[list[str], list[str]]:
    with path.open(encoding="utf-8") as handle:
        document = yaml.safe_load(handle)
    body = document["components"]["schemas"]["ErrorBody"]
    codes = list(body["properties"]["code"]["enum"])
    deprecated_map = body["properties"]["code"].get("x-phonefs-deprecated-codes") or {}
    deprecated = [code for code, meta in deprecated_map.items() if meta.get("deprecated")]
    unknown = [code for code in deprecated if code not in codes]
    if unknown:
        raise SystemExit(f"deprecated code(s) not present in enum: {unknown}")
    if not codes or not all(isinstance(code, str) and re.fullmatch(r"[A-Z][A-Z0-9_]*", code) for code in codes):
        raise SystemExit("ErrorBody.code enum missing or contains non-SCREAMING_SNAKE values")
    return codes, deprecated


def provenance(dialect_comment: str) -> list[str]:
    return [f"{dialect_comment} {line}" for line in PROVENANCE.splitlines()]


def render_go(codes: list[str], deprecated: list[str], package: str) -> str:
    lines = provenance("//") + ["", f"package {package}", "", "const ("]
    names = [f"Code{camel_case(code)}" for code in codes]
    width = max(len(name) for name in names)
    for name, code in zip(names, codes):
        # gofmt 对齐：tab + 左边距补足到最宽标识符 + "= "。
        lines.append(f'\t{name.ljust(width)} = "{code}"')
    lines.append(")")
    if deprecated:
        lines += ["", "// DeprecatedErrorCodes lists aliases kept only for compatibility."]
        lines.append("var DeprecatedErrorCodes = map[string]bool{")
        for code in deprecated:
            lines.append(f"\tCode{camel_case(code)}: true,")
        lines.append("}")
    lines.append("")
    return "\n".join(lines)


def render_kotlin(codes: list[str], deprecated: list[str], package: str) -> str:
    lines = provenance("//") + ["", f"package {package}", "", "object ErrCodes {"]
    for code in codes:
        lines.append(f'    const val {code} = "{code}"')
    if deprecated:
        lines += ["", "    /** Deprecated aliases kept only for compatibility. */"]
        joined = ", ".join(deprecated)
        lines.append(f"    val DEPRECATED: Set<String> = setOf({joined})")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def write_if_changed(path: pathlib.Path, content: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate PhoneFS error-code constants from the contract.")
    parser.add_argument("--yaml", type=pathlib.Path, default=DEFAULT_YAML)
    parser.add_argument("--go", type=pathlib.Path, default=DEFAULT_GO)
    parser.add_argument("--kotlin", type=pathlib.Path, default=DEFAULT_KOTLIN)
    parser.add_argument("--go-package", default=None)
    parser.add_argument("--kotlin-package", default="com.phonefs.core.protocol")
    args = parser.parse_args(argv)

    codes, deprecated = load_codes(args.yaml)
    go_package = args.go_package or args.go.parent.name

    go_changed = write_if_changed(args.go, render_go(codes, deprecated, go_package))
    kotlin_changed = write_if_changed(
        args.kotlin, render_kotlin(codes, deprecated, args.kotlin_package)
    )

    print(
        f"gen_error_codes: {len(codes)} codes ({len(deprecated)} deprecated); "
        f"go={'updated' if go_changed else 'unchanged'} "
        f"kotlin={'updated' if kotlin_changed else 'unchanged'}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
